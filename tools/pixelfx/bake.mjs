#!/usr/bin/env node
/**
 * Bakes the pixelfx effects listed in effects.json into sprite strips the game plays.
 *
 *   git clone https://github.com/patch-gg/pixelfx /path/to/pixelfx
 *   node tools/pixelfx/bake.mjs /path/to/pixelfx
 *
 * Writes game/assets/fx/<key>.webp (frames in a grid, cropped to what the effect
 * ever draws; lossless WebP through ffmpeg, or PNG when ffmpeg is missing) and game/src/data/pixelFxSheets.js (frame size, grid, pivot, fps).
 * Each effect is sampled from `from` to `to` seconds of its own time and
 * played `speed` times faster, always at PLAY_FPS.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';

const PLAY_FPS = 20;
const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..');
const PFX = resolve(process.argv[2] ?? process.env.PIXELFX ?? '');
if (!process.argv[2] && !process.env.PIXELFX) {
  console.error('usage: node tools/pixelfx/bake.mjs <pixelfx checkout>');
  process.exit(1);
}
const core = await import(pathToFileURL(join(PFX, 'src/core/index.js')).href);
const lib = await import(pathToFileURL(join(PFX, 'tools/lib/fxlib.mjs')).href);
const list = JSON.parse(readFileSync(join(HERE, 'effects.json'), 'utf8'));

const outDir = join(REPO, 'game/assets/fx');
mkdirSync(outDir, { recursive: true });
const sheets = {};

for (const [key, E] of Object.entries(list)) {
  if (key.startsWith('_')) continue;
  const fx = await lib.loadEffect(E.id, join(PFX, 'src/fx'));
  const { meta } = fx;
  const [W, H] = meta.size, [OX, OY] = meta.origin;
  const step = E.speed / PLAY_FPS;
  const n = Math.max(1, Math.round((E.to - E.from) / step) + 1);
  const frame = core.createFrame(W, H);
  const inst = core.createFx(fx.mod, { x: OX, y: OY, ...(E.opts ?? {}) });
  // Run up to `from` without keeping anything.
  for (let t = 0; t < E.from - 1e-9; t += 1 / 60) inst.update(Math.min(1 / 60, E.from - t));
  const frames = [];
  for (let i = 0; i < n; i++) {
    if (i > 0) inst.update(step);
    core.clearFrame(frame);
    inst.draw(frame);
    lib.edgeFade(frame);
    frames.push(core.composite(frame, new Uint8ClampedArray(W * H * 4), null));
  }
  // Crop every frame to the box the effect ever touches.
  let x0 = W, y0 = H, x1 = -1, y1 = -1;
  for (const f of frames) {
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      if (f[(y * W + x) * 4 + 3] < 8) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  const w = x1 - x0 + 1, h = y1 - y0 + 1;
  const cols = Math.min(n, Math.max(1, Math.ceil(Math.sqrt((n * h) / w))));
  const rows = Math.ceil(n / cols);
  const img = lib.canvas(cols * w, rows * h, [0, 0, 0, 0]);
  frames.forEach((f, i) => {
    const crop = new Uint8ClampedArray(w * h * 4);
    for (let y = 0; y < h; y++) crop.set(f.subarray(((y + y0) * W + x0) * 4, ((y + y0) * W + x0 + w) * 4), y * w * 4);
    img.paste(crop, w, h, (i % cols) * w, Math.floor(i / cols) * h);
  });
  const png = join(outDir, `${key}.png`);
  writeFileSync(png, img.png());
  let file = `${key}.png`;
  const webp = spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', png, '-c:v', 'libwebp', '-lossless', '1', '-compression_level', '6', join(outDir, `${key}.webp`)]);
  if (!webp.error && webp.status === 0) {
    rmSync(png);
    file = `${key}.webp`;
  }
  sheets[key] = { file, w, h, cols, frames: n, fps: PLAY_FPS, pivot: [OX - x0, OY - y0], source: E.id };
  console.log(`${key.padEnd(10)} ${E.id.padEnd(24)} ${n} frames ${w}x${h} (${cols}x${rows})`);
}

const js = `// Generated by tools/pixelfx/bake.mjs from pixelfx (https://github.com/patch-gg/pixelfx, MIT). Do not edit.
// key: { file, w, h (frame size), cols (frames per row), frames, fps, pivot (the effect's origin in the frame), source }
export const PIXEL_FX_SHEETS = {
${Object.entries(sheets).map(([k, v]) => `  ${k}: ${JSON.stringify(v).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'").replace(/,(?=\S)/g, ', ').replace(/^\{/, '{ ').replace(/\}$/, ' }')},`).join('\n')}
};
`;
writeFileSync(join(REPO, 'game/src/data/pixelFxSheets.js'), js);
console.log('-> game/assets/fx/, game/src/data/pixelFxSheets.js');
